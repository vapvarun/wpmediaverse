#!/usr/bin/env bash
# bin/local-ci.sh — local-CI gate for WPMediaVerse.
#
# Single entry point that runs every quality + correctness + journey
# check in the right order. Designed to be runnable from a fresh clone
# without GitHub Actions or any external infrastructure.
#
# Usage:
#   composer ci                         # via composer script
#   bash bin/local-ci.sh                # direct, all stages
#   bash bin/local-ci.sh --no-journeys  # skip browser-dependent stages
#   bash bin/local-ci.sh --quick        # lint + coding-rules only (~10s)
#
# Exit 0 = green; non-zero = at least one stage failed (the offending
# stage's stdout/stderr was already printed). Each stage has a numeric
# tag (1.x = static, 2.x = security, 3.x = manifest, 4.x = journeys)
# so you can scroll back to the first red.
#
# Generated by wp-plugin-onboard skill. Edit freely — this is your
# plugin's CI orchestrator, not skill state.

set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PLUGIN_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
PLUGIN_SLUG="$(basename "$PLUGIN_DIR")"

cd "$PLUGIN_DIR"

MODE="full"
SITE_URL="${LOCAL_CI_SITE_URL:-http://mediaverse.local}"

while [ $# -gt 0 ]; do
  case "$1" in
    --no-journeys) MODE="no-journeys" ;;
    --quick)       MODE="quick" ;;
    --site)        SITE_URL="$2"; shift ;;
    *) echo "Unknown flag: $1"; exit 2 ;;
  esac
  shift
done

# ─── helpers ─────────────────────────────────────────────────────────────────

FAILED=()
GREEN="\033[0;32m"; RED="\033[0;31m"; YELLOW="\033[0;33m"; DIM="\033[2m"; RESET="\033[0m"

step() { printf "${DIM}[%s]${RESET} %s\n" "$1" "${@:2}"; }
pass() { printf "${GREEN}✓${RESET}  %s\n" "$*"; }
fail() { printf "${RED}✗${RESET}  %s\n" "$*"; FAILED+=("$1"); }
warn() { printf "${YELLOW}!${RESET}  %s\n" "$*"; }

run_stage() {
  local tag="$1"; local label="$2"; shift 2
  step "$tag" "$label"
  if "$@" > /tmp/local-ci-$$.log 2>&1; then
    pass "$label"
  else
    fail "$tag $label"
    cat /tmp/local-ci-$$.log | sed 's/^/    /'
  fi
  rm -f /tmp/local-ci-$$.log
}

echo "=== WPMediaVerse local-CI ==="
echo "Mode: $MODE  ·  Site: $SITE_URL"
echo ""

# ─── 1.x — Static checks (fast, no runtime needed) ───────────────────────────

step "1.1" "PHP lint (every changed-source PHP file)"
PHP_LINT_FAILED=0
while IFS= read -r -d '' file; do
  if ! php -l "$file" > /dev/null 2>&1; then
    fail "1.1 PHP lint: $file"
    php -l "$file" 2>&1 | sed 's/^/    /'
    PHP_LINT_FAILED=1
  fi
done < <(find . -type f -name '*.php' \
          -not -path './vendor/*' \
          -not -path './node_modules/*' \
          -not -path './tests/*' \
          -not -path './build/*' \
          -not -path './dist/*' \
          -not -path './.git/*' \
          -print0)
[ "$PHP_LINT_FAILED" = "0" ] && pass "PHP lint clean"

if [ "$MODE" = "quick" ]; then
  step "QUICK" "skipping WPCS / PHPStan / wppqa / journeys"
else
  if [ -f phpcs.xml ] || [ -f .phpcs.xml.dist ]; then
    if [ -x vendor/bin/phpcs ]; then
      run_stage "1.2" "WPCS (phpcs)" composer phpcs
    else
      warn "1.2 WPCS skipped — run 'composer install' first"
    fi
  fi

  if [ -f phpstan.neon ] || [ -f phpstan.neon.dist ]; then
    if [ -x vendor/bin/phpstan ]; then
      run_stage "1.3" "PHPStan static analysis" composer phpstan
    else
      warn "1.3 PHPStan skipped — vendor/bin/phpstan not present"
    fi
  fi
fi

# 1.4 — CSS token-contract (phantom tokens + dead dark-mode selectors). Static,
# fast, always runs (incl. --quick). Catches the dark-mode CSS bug class that
# journeys / WPCS / PHPStan are blind to — see bin/css-token-contract.sh.
if [ -x bin/css-token-contract.sh ]; then
  run_stage "1.4" "CSS token-contract" bash bin/css-token-contract.sh
fi

# 1.5 — Duplication gate (no NEW copy-pasted method bodies vs the frozen
# baseline). Stops "reinventing the same section again" — reuse a shared
# helper/partial or re-bless. See bin/duplication-gate.sh.
if [ -x bin/duplication-gate.sh ]; then
  run_stage "1.5" "Duplication gate (no new copy-paste)" bash bin/duplication-gate.sh
fi

# 1.6 — Journey coverage: every release-critical feature must have an executable
# journey (audit/journeys/REQUIRED-COVERS.txt). Stops a feature shipping — or
# being silently dropped — with no end-to-end test (the boost-drop class). The
# journeys themselves run at stage 4.1; this asserts the critical ones exist.
if [ -x bin/journey-coverage.sh ]; then
  run_stage "1.6" "Journey coverage (critical features have a journey)" bash bin/journey-coverage.sh
fi

# 1.7 — Template-style check: no STATIC inline styles / hardcoded hex in markup
# (templates, block render.php, HTML-echoing includes). Closes the hole the CSS
# token-contract gate can't see — it scans .css files, not inline style="…"
# attributes. Pure visibility toggles (display:none) and var(--token,#fallback)
# are allowed; cosmetic inline color/spacing/font/border is not. See
# bin/template-style-check.sh.
if [ -x bin/template-style-check.sh ]; then
  run_stage "1.7" "Template-style check (no inline cosmetic CSS)" bash bin/template-style-check.sh
fi

# ─── 2.x — Security + Architecture (always cheap) ────────────────────────────

if [ -x bin/coding-rules-check.sh ]; then
  run_stage "2.1" "Coding-rules check" bash bin/coding-rules-check.sh
fi

if [ -x bin/architecture-checks.sh ]; then
  run_stage "2.2" "Architecture invariants (Free/Pro contract)" bash bin/architecture-checks.sh
fi

# Settings API contract test — catches the d986525 dm_access bug class:
# duplicate register_setting() calls, dropdown choices vs sanitizer whitelist
# drift, sanitize_text_field used on fixed-choice dropdowns.
if [ -x vendor/bin/phpunit ] && [ -f tests/unit/SettingsContractTest.php ]; then
  if [ -f /tmp/wordpress-tests-lib/includes/functions.php ]; then
    run_stage "2.3" "Settings API contract (PHPUnit)" composer test:contract
  else
    warn "2.3 Settings contract test skipped — WP_TESTS_DIR (/tmp/wordpress-tests-lib) not installed"
  fi
fi

# ─── 2.5 — ux-audit (ux-foundation drift detection) ──────────────────────────
# Runs the ux-audit.sh script (vendored from ~/.claude/skills/ux-audit/) to
# catch design-system drift on every push: inline <style>/<script> in PHP,
# raw hex outside :root tokens, native window.confirm/alert/prompt, theme
# sidebar hidden via display:none. Block-severity violations fail the gate.
# Advisory findings (outline:none without :focus-visible, raw margin-left,
# dashicons in new code, >3 breakpoints) print but don't fail — they go on
# the next release's polish list.
#
# Why this gate matters: the 1.4.0 release-prep hardening pass surfaced 14
# Free + 6 Pro accumulated drift items that wppqa caught in milliseconds
# but had been there for months because nothing enforced them. ux-audit
# closes that gap — every push reverifies design-system compliance.
if [ -x bin/ux-audit.sh ] && [ "$MODE" != "quick" ]; then
  step "2.5" "UX audit (ux-foundation drift)"
  UX_REPORT="audit/ux-audit-$(date +%Y-%m-%d).md"
  mkdir -p audit
  if bash bin/ux-audit.sh "$(pwd)" > "$UX_REPORT" 2>&1; then
    BLOCK_TAIL="$(grep -E '^\*\*Block-severity violations' "$UX_REPORT" | head -1)"
    pass "UX audit (ux-foundation drift) — $BLOCK_TAIL → $UX_REPORT"
  else
    fail "2.5 UX audit (ux-foundation drift) — block-severity violations found, see $UX_REPORT"
  fi
fi

# ─── 2.4 — wppqa baseline freshness ──────────────────────────────────────────
# wppqa is an MCP bug-finder that catches REST/JS contract drift, silent UI
# bugs, and admin-rule violations in ~120ms. It's invocable only from
# Claude Code (no CLI), so this stage can't run it directly. Instead, it
# enforces that a baseline exists AND is fresh — if either fails, push
# is blocked with instructions to refresh via the skill.
#
# Hard rule #6 of wp-plugin-onboard: "wppqa is the bug-finder, manifest is
# the map." Skipping wppqa is how the 1.2.2 session shipped 14 bugs that
# wppqa would have caught structurally.
if [ "$MODE" != "quick" ]; then
  WPPQA_MAX_AGE_DAYS="${WPPQA_MAX_AGE_DAYS:-14}"
  WPPQA_BASELINE_GLOB="audit/runs/*wppqa-baseline*.md audit/wppqa-baseline-*/SUMMARY.md"
  LATEST_BASELINE=""
  LATEST_TS=0
  for pattern in $WPPQA_BASELINE_GLOB; do
    for f in $pattern; do
      [ -f "$f" ] || continue
      file_ts=$(stat -f %m "$f" 2>/dev/null || stat -c %Y "$f" 2>/dev/null || echo 0)
      if [ "$file_ts" -gt "$LATEST_TS" ]; then
        LATEST_TS="$file_ts"
        LATEST_BASELINE="$f"
      fi
    done
  done

  if [ -z "$LATEST_BASELINE" ]; then
    step "2.4" "wppqa baseline — MISSING"
    printf "${RED}✗${RESET}  No wppqa baseline found.\n"
    printf "    Skill rule #6: wppqa is the bug-finder, manifest is the map.\n"
    printf "    Run via Claude Code: mcp__wp-plugin-qa__wppqa_audit_plugin --plugin_path=\"\$(pwd)\"\n"
    printf "    Save the result to audit/runs/\$(date +%%Y-%%m-%%d)-wppqa-baseline-SUMMARY.md\n"
    printf "    Bypass for emergencies: SKIP_LOCAL_CI=1 git push\n"
    FAILED+=("2.4 wppqa baseline missing")
  else
    NOW_TS=$(date -u +%s)
    AGE_DAYS=$(( (NOW_TS - LATEST_TS) / 86400 ))
    if [ "$AGE_DAYS" -gt "$WPPQA_MAX_AGE_DAYS" ]; then
      step "2.4" "wppqa baseline — STALE (${AGE_DAYS} days old, cap ${WPPQA_MAX_AGE_DAYS})"
      printf "${RED}✗${RESET}  Latest baseline: %s (%d days old)\n" "$LATEST_BASELINE" "$AGE_DAYS"
      printf "    Refresh via Claude Code: mcp__wp-plugin-qa__wppqa_audit_plugin\n"
      printf "    Override the cap: WPPQA_MAX_AGE_DAYS=30 composer ci:no-journeys\n"
      printf "    Bypass for emergencies: SKIP_LOCAL_CI=1 git push\n"
      FAILED+=("2.4 wppqa baseline stale (${AGE_DAYS}d)")
    else
      pass "2.4 wppqa baseline fresh (${AGE_DAYS}d old, cap ${WPPQA_MAX_AGE_DAYS}d) — ${LATEST_BASELINE}"
    fi
  fi
fi

# ─── 3.x — Manifest freshness ────────────────────────────────────────────────

if [ "$MODE" != "quick" ]; then
  if [ -f audit/manifest.json ]; then
    if jq . audit/manifest.json > /dev/null 2>&1; then
      pass "3.1 Manifest is valid JSON"

      MANIFEST_AT="$(jq -r '.generated.at // empty' audit/manifest.json)"
      if [ -n "$MANIFEST_AT" ]; then
        AGE_DAYS=$(( ($(date -u +%s) - $(date -juf "%Y-%m-%dT%H:%M:%SZ" "$MANIFEST_AT" +%s 2>/dev/null || echo 0)) / 86400 ))
        if [ "$AGE_DAYS" -gt 30 ]; then
          warn "3.1 Manifest is ${AGE_DAYS}d old — refresh via /wp-plugin-onboard --refresh"
        fi
      fi
    else
      fail "3.1 Manifest JSON invalid"
    fi
  else
    warn "3.1 No audit/manifest.json — run /wp-plugin-onboard"
  fi
fi

# ─── 4.x — Journeys (browser-dependent, can be skipped) ──────────────────────

if [ "$MODE" = "full" ]; then
  if [ -d audit/journeys ] && [ -x bin/run-journeys.sh ]; then
    if curl -fsS "$SITE_URL" > /dev/null 2>&1; then
      run_stage "4.1" "Customer journeys (browser+REST+DB)" bash bin/run-journeys.sh --site "$SITE_URL"
    else
      warn "4.1 Journeys skipped — site $SITE_URL is not reachable"
    fi
  fi
fi

# ─── Summary ─────────────────────────────────────────────────────────────────

echo ""
echo "=== Summary ==="
if [ ${#FAILED[@]} -eq 0 ]; then
  printf "${GREEN}local-CI green${RESET}\n"
  exit 0
else
  printf "${RED}local-CI failed: %d stage(s)${RESET}\n" "${#FAILED[@]}"
  for stage in "${FAILED[@]}"; do
    printf "  ${RED}✗${RESET} %s\n" "$stage"
  done
  exit 1
fi
